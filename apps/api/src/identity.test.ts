import assert from "node:assert/strict";
import test from "node:test";
import {randomUUID} from "node:crypto";
import {authenticator} from "otplib";
import {connectDatabase,schema} from "@amlaklink/database";
import {buildApp} from "./app";
import {canSubmitListing} from "./access";
import {encryptTotp,newTotpSecret,passwordHash} from "./security";
import {type SendCode} from "./mail";
test("listing capability enforces contact verification and organization scope",()=>{
 assert.equal(canSubmitListing({verified:false,advertiserEnabled:true},"private"),false);
 assert.equal(canSubmitListing({verified:true,advertiserEnabled:false},"private"),false);
 assert.equal(canSubmitListing({verified:true,advertiserEnabled:true},"private"),true);
 assert.equal(canSubmitListing({verified:true,advertiserEnabled:false,agencyActive:false,memberRole:"owner"},"agency"),false);
 assert.equal(canSubmitListing({verified:true,advertiserEnabled:false,agencyActive:true,memberRole:"agent"},"agency"),true);
 assert.equal(canSubmitListing({verified:true,advertiserEnabled:false,agencyActive:true,memberRole:"visitor"},"agency"),false);
});
test("PostgreSQL identity lifecycle, MFA, and cross-agency revocation", {skip:!process.env.DATABASE_URL},async()=>{
 const {db,sql}=connectDatabase();
 const codes=new Map<string,string>();
 const mail:SendCode=async(email,_purpose,code)=>{codes.set(email,code);};
 const app=buildApp({db,mailer:mail});
 const unique=randomUUID().slice(0,8);
 const ownerEmail="owner-"+unique+"@example.test",agentEmail="agent-"+unique+"@example.test";
 const staffEmail="reviewer-"+unique+"@example.test";
 const call=async(method:"GET"|"POST"|"PATCH",path:string,body?:object,token?:string)=>{
  const response=await app.inject({method,url:path,headers:token?{authorization:"Bearer "+token}:{},...(body?{payload:body}:{})});
  return {status:response.statusCode,data:response.json() as Record<string,any>};
 };
 const register=async(email:string)=>{
  const response=await call("POST","/v1/auth/register",{email,password:"SecurePass1299!",displayName:"Test User",locale:"fa"});
  assert.equal(response.status,200);
  assert.equal(response.data.requiresVerification,true);
  return response;
 };
 const verify=async(email:string)=>{
  const response=await call("POST","/v1/auth/verify",{email,code:codes.get(email)});
  assert.equal(response.status,200);return response.data.token as string;
 };
 try{
  assert.equal((await call("GET","/ready")).status,200);
  await register(ownerEmail);
  assert.equal((await call("POST","/v1/auth/login",{email:ownerEmail,password:"SecurePass1299!"})).status,403);
  assert.equal((await call("POST","/v1/advertiser/activate",{acceptedRules:true})).status,401);
  const ownerToken=await verify(ownerEmail);
  assert.equal((await call("GET","/v1/me",undefined,ownerToken)).data.user.verified,true);
  assert.equal((await call("GET","/v1/advertiser/capabilities",undefined,ownerToken)).data.canSubmitListing,false);
  assert.equal((await call("POST","/v1/agents/apply",{acceptedProfessionalRules:true},ownerToken)).status,200);
  assert.equal((await call("GET","/v1/advertiser/capabilities",undefined,ownerToken)).data.independentAgentStatus,"pending");
  assert.equal((await call("POST","/v1/advertiser/activate",{acceptedRules:true},ownerToken)).status,200);
  assert.equal((await call("GET","/v1/advertiser/capabilities",undefined,ownerToken)).data.canSubmitListing,true);
  await register(agentEmail);
  const agentToken=await verify(agentEmail);
  const first=await call("POST","/v1/agencies/apply",{name:"Test Realty A",provinceId:"kabul"},ownerToken);
  const other=await call("POST","/v1/agencies/apply",{name:"Test Realty B",provinceId:"herat"},agentToken);
  assert.equal(first.status,200);assert.equal(other.status,200);
  const a=first.data.id as string,b=other.data.id as string;
  assert.equal((await call("GET","/v1/agencies/"+a+"/workspace",undefined,ownerToken)).status,403);
  assert.equal((await call("GET","/v1/agencies/"+b+"/workspace",undefined,ownerToken)).status,403);
  const staffSecret=newTotpSecret();
  const [staffUser]=await db.insert(schema.staff).values({email:staffEmail,displayName:"Reviewer",passwordHash:await passwordHash("SecureStaffPassword123!"),role:"verification",totpSecretEncrypted:encryptTotp(staffSecret)}).returning();
  const loginStaff=await call("POST","/v1/staff/auth/login",{email:staffEmail,password:"SecureStaffPassword123!",totp:authenticator.generate(staffSecret)});
  assert.equal(loginStaff.status,200);
  const staffToken=loginStaff.data.token as string;
  assert.equal((await call("GET","/v1/admin/agents",undefined,staffToken)).data.items.some((p:{email:string})=>p.email===ownerEmail),true);
  assert.equal((await call("POST","/v1/admin/agents/"+(await call("GET","/v1/me",undefined,ownerToken)).data.user.id+"/decision",{decision:"approve",reason:"Reviewed professional credentials offline"},staffToken)).status,200);
  assert.equal((await call("GET","/v1/advertiser/capabilities",undefined,ownerToken)).data.independentAgentStatus,"approved");
  assert.equal((await call("GET","/v1/me",undefined,staffToken)).status,401);
  assert.equal((await call("GET","/v1/staff/me",undefined,ownerToken)).status,401);
  assert.equal((await call("GET","/v1/admin/agencies",undefined,agentToken)).status,401);
  assert.equal((await call("POST","/v1/admin/agencies/"+a+"/decision",{decision:"approve",reason:"Validated with submitted documentation"},staffToken)).status,200);
  assert.equal((await call("POST","/v1/admin/agencies/"+b+"/decision",{decision:"approve",reason:"Validated second agency documentation"},staffToken)).status,200);
  assert.equal((await call("GET","/v1/agencies/"+a+"/workspace",undefined,ownerToken)).status,200);
  assert.equal((await call("GET","/v1/agencies/"+a+"/workspace",undefined,agentToken)).status,403);
  assert.equal((await call("GET","/v1/agencies/"+b+"/workspace",undefined,ownerToken)).status,403);
  const add=await call("POST","/v1/agencies/"+a+"/members",{email:agentEmail,role:"agent"},ownerToken);
  assert.equal(add.status,200);
  assert.equal((await call("GET","/v1/agencies/"+a+"/workspace",undefined,agentToken)).status,403);
  assert.equal((await call("POST","/v1/agencies/"+a+"/invitation/accept",{},agentToken)).status,200);
  assert.equal((await call("GET","/v1/agencies/"+a+"/workspace",undefined,agentToken)).status,200);
  const members=await call("GET","/v1/agencies/"+a+"/members",undefined,ownerToken);
  const agentMember=(members.data.items as {id:string;role:string;userId:string}[]).find(m=>m.userId===add.data.userId);
  assert.ok(agentMember);
  assert.equal((await call("POST","/v1/agencies/"+a+"/members",{email:ownerEmail,role:"manager"},agentToken)).status,403);
  assert.equal((await call("POST","/v1/agencies/"+a+"/members/"+agentMember!.id+"/revoke",{},ownerToken)).status,200);
  assert.equal((await call("GET","/v1/agencies/"+a+"/workspace",undefined,agentToken)).status,403);
  assert.equal((await call("GET","/v1/agencies/"+b+"/workspace",undefined,agentToken)).status,200);
  assert.equal((await call("POST","/v1/auth/recover",{email:ownerEmail})).status,200);
  const reset=await call("POST","/v1/auth/recover/complete",{email:ownerEmail,code:codes.get(ownerEmail),newPassword:"AnotherSecurePass123!"});
  assert.equal(reset.status,200);
  assert.equal((await call("GET","/v1/me",undefined,ownerToken)).status,401);
  assert.equal((await call("POST","/v1/auth/login",{email:ownerEmail,password:"AnotherSecurePass123!"})).status,200);
  assert.equal((await call("POST","/v1/staff/auth/login",{email:staffEmail,password:"SecureStaffPassword123!",totp:authenticator.generate(staffSecret)})).status,401);
  assert.ok(staffUser.id);
 }finally{await app.close();await sql.end();}
});
